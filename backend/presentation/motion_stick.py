"""Builder for ``StickScene`` (MOTION_GRAPHICS_PLAN.md M7, extended
STICK_WORLD_PLAN.md SW2): an SVG-rigged stick figure acting out a simple
action with a line-drawn prop, on a whiteboard/paper/night/underwater ground
-- or, dressed for an `era` and standing over a generated `bg` picture, in
`stick_world`'s period-illustrated world. Directive `[stick: action=<pose> |
scene=<short English scene> | era=<eras key> | outfit=<spec> ; <spec> |
figures=<1-3> | bg=<picture prompt> | caption=<optional short text> |
seconds=N]` (presentation/script.py::directive_beats) -> a ``stick_scene``
beat -> this module's job spec. Registered in ``presentation/motion.py::
BUILDERS``.

The ``scene`` text never appears on screen -- ``ground_for_scene`` is the only
thing that reads it, to pick the background, exactly as the Architecture
says (unaffected by ``bg``, which draws a real picture instead of a plain
ground; see below). A render the engine cannot make falls back to a plain
PIL stick-figure still (``render_stick_still``, used by ``motion.
render_fallback``), drawn over the beat's own already-generated background
picture when there is one, rather than a fresh ComfyUI generation: by the
time a motion beat's failure is known, ComfyUI's own generation pass over
the plan's beats has already run.

``era``/``outfit``/``bg`` (STICK_WORLD_PLAN.md SW2) read against the ONE
shared vocabulary, ``motion/src/stick_world.json`` (``_load_vocab``):
``outfit`` is one spec per figure (``;`` between figures), each spec's
``+``-joined tokens normalised against the vocabulary (``normalize_outfit``
-- an unknown token dropped, a second token of a category already kept
dropped too); ``era`` alone fills whichever figure named no outfit of its
own from the era's own defaults (``_build_people``). A ``bg`` prompt needs a
real picture first -- ``expand_stick_backgrounds``/``annotate_stick_
backgrounds``/``drop_stick_background_subs`` are this module's own copy of
``motion_collage.py``'s ``expand_collages``/``annotate_collage_assets``/
``drop_collage_subs`` pattern (one zero-length ``broll_image`` sub-beat,
generated by ``assets_stage.generate_assets`` exactly like any other B-roll
still, wired in ``director.py`` beside the collage calls) -- and no picture
at all, same as no ``bg``, simply means the plain ground of today; neither
failure path may ever raise.
"""

import json
import logging
import uuid
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

from config import BASE_DIR

from .models import Asset, Beat
from .motion import MotionContext, _beat_duration

logger = logging.getLogger("presentation.motion_stick")

# The ONE shared vocabulary (STICK_WORLD_PLAN.md "The shared vocabulary"):
# body/head/held/hair piece names and the `eras` table -- resolved from this
# module the way presentation/motion.py resolves its own MOTION_DIR.
STICK_WORLD_JSON = BASE_DIR / "motion" / "src" / "stick_world.json"

# The fixed suffix every `bg` prompt gets (STICK_WORLD_PLAN.md SW2) -- never
# a camera/lens/"shot on" word, per the "no camera in shots" rule.
_BG_SUFFIX = ("a wide view of the place with nobody in it, an open floor "
             "across the lower fifth")
# `background` data: URI cap (STICK_WORLD_PLAN.md SW2): downscaled to at
# most this on the long side, JPEG quality ~85.
_BG_MAX_SIDE = 1920

ACTIONS = ("idle", "walk", "run", "point", "shrug", "think", "cheer", "fall",
          "sit", "scared", "swim", "climb")
PROPS = ("ship", "wave", "house", "tree", "phone", "money", "car", "mountain",
         "door", "table", "book", "sun", "moon", "rain")

_UNDERWATER_WORDS = ("underwater", "under water", "sea", "ocean", "undersea",
                     "deep sea", "seabed", "seafloor", "scuba", "diving")
_NIGHT_WORDS = ("night", "midnight", "moonlit", "after dark", "nighttime")


def normalize_action(action: Optional[str]) -> str:
    value = (action or "").strip().lower()
    return value if value in ACTIONS else "idle"


def normalize_prop(prop: Optional[str]) -> str:
    value = (prop or "").strip().lower()
    return value if value in PROPS else "none"


def ground_for_scene(scene: Optional[str]) -> str:
    """The `scene` text is never drawn -- it only picks the ground/background:
    underwater/sea -> wavy blue lines, night -> dark paper, else whiteboard."""
    text = (scene or "").strip().lower()
    if any(word in text for word in _UNDERWATER_WORDS):
        return "underwater"
    if any(word in text for word in _NIGHT_WORDS):
        return "night"
    return "whiteboard"


# --- the shared vocabulary (STICK_WORLD_PLAN.md) ---------------------------

_vocab_cache: Optional[Dict[str, Any]] = None


def _load_vocab() -> Dict[str, Any]:
    """``stick_world.json``, read once and memoised per process -- the same
    body/head/held/hair piece names and ``eras`` table ``StickScene.tsx``
    itself imports. An empty, harmless vocabulary (every lookup below then
    finds nothing, and every figure comes back plain) on any read/parse
    failure -- never raises."""
    global _vocab_cache
    if _vocab_cache is not None:
        return _vocab_cache
    try:
        _vocab_cache = json.loads(STICK_WORLD_JSON.read_text(encoding="utf-8"))
    except Exception as e:  # noqa: BLE001 - a bad vocabulary file must never fail a render
        logger.warning("Stick World vocabulary at %s could not be read: %s", STICK_WORLD_JSON, e)
        _vocab_cache = {"body": [], "head": [], "held": [], "hair": [], "eras": {}}
    return _vocab_cache


def reset_vocab_cache() -> None:
    """Tests call this between cases; ``_load_vocab`` otherwise memoises per process."""
    global _vocab_cache
    _vocab_cache = None


def _piece_categories(vocab: Dict[str, Any]) -> Dict[str, str]:
    cat_of: Dict[str, str] = {}
    for category in ("body", "head", "held", "hair"):
        for piece in vocab.get(category, []):
            cat_of[piece] = category
    return cat_of


def normalize_outfit(spec: Optional[str], vocab: Optional[Dict[str, Any]] = None) -> str:
    """An outfit spec's order-free ``+``-joined tokens, normalised against
    the vocabulary (STICK_WORLD_PLAN.md "The shared vocabulary"): an unknown
    token is dropped, and a second token of a category already kept is
    dropped too -- one piece per body/head/held/hair. "" for a blank spec or
    one whose tokens matched nothing."""
    vocab = vocab or _load_vocab()
    cat_of = _piece_categories(vocab)
    seen: set = set()
    kept: List[str] = []
    for raw in (spec or "").split("+"):
        token = raw.strip().lower()
        if not token:
            continue
        category = cat_of.get(token)
        if category is None or category in seen:
            continue
        seen.add(category)
        kept.append(token)
    return "+".join(kept)


def compose_bg_prompt(data: Dict[str, Any], vocab: Optional[Dict[str, Any]] = None) -> str:
    """``bg`` + the era's own ``bg`` words (when ``era`` is a known
    vocabulary key) + the fixed "nobody in it" suffix (STICK_WORLD_PLAN.md
    SW2) -- the raw picture prompt, before the caller's own art-style/genre
    look is stamped on. "" when the beat named no ``bg`` at all -- nothing
    to generate; the scene draws over today's plain ground instead."""
    bg = (data.get("bg") or "").strip()
    if not bg:
        return ""
    vocab = vocab or _load_vocab()
    era = data.get("era")
    era_words = (vocab.get("eras", {}).get(era) or {}).get("bg", "") if era else ""
    parts = [bg]
    if era_words:
        parts.append(era_words)
    parts.append(_BG_SUFFIX)
    return ", ".join(p for p in parts if p)


def _build_people(data: Dict[str, Any], figures: int, era: Optional[str],
                  vocab: Dict[str, Any]) -> Optional[List[Dict[str, str]]]:
    """Beat.data's ``outfits`` (one spec per figure, in order) and/or
    ``era`` (fills whichever figure named none of its own, from the era's
    own defaults) -> the ``people`` prop StickScene takes, each spec
    normalised against the vocabulary. None when the beat named neither --
    the plain stick figure(s) of today, unchanged."""
    outfits_raw = data.get("outfits") or []
    era_people = (vocab.get("eras", {}).get(era) or {}).get("people", []) if era else []
    if not outfits_raw and not era_people:
        return None
    people: List[Dict[str, str]] = []
    for i in range(figures):
        spec = outfits_raw[i] if i < len(outfits_raw) else (
            era_people[i] if i < len(era_people) else "")
        normalized = normalize_outfit(spec, vocab) if spec else ""
        people.append({"outfit": normalized} if normalized else {})
    return people


def measure_bg_luma(path: str) -> Optional[float]:
    """0-255 mean luma of the picture's lower-middle band -- where the
    figures' feet sit -- for StickScene's ``bgLuma`` prop (SW1 picks light
    or dark strokes, with a contrasting halo, from it). None on any
    failure; never raises."""
    try:
        from PIL import Image
        with Image.open(path) as img:
            gray = img.convert("L")
            w, h = gray.size
            x0, x1 = round(w * 0.25), round(w * 0.75)
            y0, y1 = round(h * 0.65), h
            if x1 <= x0 or y1 <= y0:
                return None
            pixels = list(gray.crop((x0, y0, x1, y1)).getdata())
            return sum(pixels) / len(pixels) if pixels else None
    except Exception as e:  # noqa: BLE001 - a luma read must never fail the render
        logger.warning("Stick background luma for %s failed: %s", path, e)
        return None


def _background_data_uri(path: str) -> Optional[str]:
    """The generated background still as a ``data:`` JPEG URI for
    StickScene's ``background`` prop -- downscaled to at most ``_BG_MAX_SIDE``
    on the long side, quality ~85 (a small local copy of motion_collage.py's
    own ``_data_uri_rgb`` idea; that module is edited in parallel elsewhere,
    so copied rather than imported). None on any failure; never raises."""
    try:
        import base64
        import io

        from PIL import Image
        with Image.open(path) as src:
            rgb = src.convert("RGB")
            w, h = rgb.size
            scale = min(1.0, _BG_MAX_SIDE / float(max(w, h)))
            if scale < 0.999:
                rgb = rgb.resize((max(1, round(w * scale)), max(1, round(h * scale))),
                                 Image.Resampling.LANCZOS)
            buf = io.BytesIO()
            rgb.save(buf, format="JPEG", quality=85)
        b64 = base64.b64encode(buf.getvalue()).decode("ascii")
        return f"data:image/jpeg;base64,{b64}"
    except Exception as e:  # noqa: BLE001 - must never fail the render
        logger.warning("Stick background image data for %s failed: %s", path, e)
        return None


# --- the background picture: expand, annotate, drop ------------------------
# This module's own copy of motion_collage.py's expand_collages/annotate_
# collage_assets/drop_collage_subs pattern (that module is edited in
# parallel elsewhere, so copied rather than shared) -- see the module
# docstring.

def expand_stick_backgrounds(beats: Sequence[Beat], genre: str, genre_secondary: Optional[str],
                             art_style: str) -> List[Beat]:
    """A ``stick_scene`` beat whose ``bg`` names a scene keeps its own place
    on the timeline and also gets one zero-length ``broll_image`` sub-beat
    appended for the background picture -- zero length so it costs nothing
    in any coverage/budget math downstream (``presentation.live``'s own
    trim). ``assets_stage.generate_assets`` then makes a real picture for it
    exactly like any other B-roll beat; ``annotate_stick_backgrounds``
    stashes the file path and its measured ``bg_luma`` back on the parent;
    ``drop_stick_background_subs`` keeps the sub-beat's own asset out of
    placement. A ``stick_scene`` beat with no ``bg`` is left untouched -- it
    draws over today's plain ground, as before."""
    from . import genre as genre_mod
    out: List[Beat] = []
    for beat in beats:
        if beat.kind != "stick_scene":
            out.append(beat)
            continue
        data = beat.data or {}
        raw_prompt = compose_bg_prompt(data)
        if not raw_prompt:
            out.append(beat)
            continue
        beat_id = beat.id or f"stick_{uuid.uuid4().hex[:6]}"
        parent = beat if beat.id else beat.model_copy(update={"id": beat_id})
        out.append(parent)
        prompt = genre_mod.apply_look(raw_prompt, genre, genre_secondary, art_style) or raw_prompt
        out.append(parent.model_copy(update={
            "id": f"{beat_id}_bg",
            "kind": "broll_image",
            "end_s": parent.start_s,
            "image_prompt": prompt,
            "video_prompt": None,
            "text": None,
            "subtext": None,
            "place": None,
            "data": {"stick_bg_sub": True, "parent_beat": beat_id},
            "planned_duration_s": None,
            "shows_character": False,
            "sfx": None,
        }))
    return out


def annotate_stick_backgrounds(beats: Sequence[Beat], generated: Sequence[Asset]) -> None:
    """After the background still already exists (``assets_stage.
    generate_assets``), stash a ``stick_scene`` beat's own picture path and
    its measured luma on its ``data`` -- ``build_stick_scene`` and
    ``motion.render_fallback``'s ``stick_scene`` branch both read them from
    there, so neither needs ``generated`` threaded through
    ``MotionContext``. Mutates ``beats`` in place; never raises."""
    try:
        by_id = {a.beat_id: a for a in generated}
        for beat in beats:
            if beat.kind != "stick_scene":
                continue
            asset = by_id.get(f"{beat.id}_bg")
            if asset is not None and Path(asset.path).exists():
                beat.data["bg_image"] = asset.path
                beat.data["bg_luma"] = measure_bg_luma(asset.path)
    except Exception as e:  # noqa: BLE001 - annotation must never fail the render
        logger.warning("annotate_stick_backgrounds failed: %s", e)


def drop_stick_background_subs(assets: Sequence[Asset], beats: Sequence[Beat]) -> List[Asset]:
    """A ``stick_scene`` background sub-beat's picture is the picture the
    scene is drawn over *inside* the StickScene composition, never its own
    cutaway. Drops its asset right before ``placement.place_broll``; every
    other asset is returned untouched."""
    sub_ids = {b.id for b in beats if (b.data or {}).get("stick_bg_sub")}
    if not sub_ids:
        return list(assets)
    return [a for a in assets if a.beat_id not in sub_ids]


# --- the builder -------------------------------------------------------------

def build_stick_scene(beat: Beat, ctx: MotionContext) -> Optional[Dict[str, Any]]:
    """``stick_scene`` beat -> a StickScene job."""
    data = beat.data or {}
    action = normalize_action(data.get("action"))
    prop = normalize_prop(data.get("prop"))
    scene = data.get("scene") or beat.topic or ""
    ground = ground_for_scene(scene)
    try:
        figures = int(data.get("figures", 1))
    except (TypeError, ValueError):
        figures = 1
    figures = max(1, min(3, figures))
    caption = (data.get("caption") or "").strip()[:60] or None
    duration_s = _beat_duration(beat)
    frames = max(1, round(duration_s * ctx.fps))

    vocab = _load_vocab()
    era = data.get("era")
    if era and era not in vocab.get("eras", {}):
        era = None
    people = _build_people(data, figures, era, vocab)

    props: Dict[str, Any] = {
        "theme": ctx.theme,
        "action": action,
        "prop": prop,
        "ground": ground,
        "figures": figures,
        "caption": caption,
    }
    if era:
        props["era"] = era
    if people:
        props["people"] = people

    bg_image = data.get("bg_image")
    if bg_image and Path(bg_image).exists():
        src = _background_data_uri(bg_image)
        if src:
            props["background"] = src
            luma = data.get("bg_luma")
            if luma is not None:
                props["bgLuma"] = luma

    return {
        "composition": "StickScene",
        "props": props,
        "width": ctx.width, "height": ctx.height, "fps": ctx.fps, "frames": frames,
        "transparent": False,
    }


# --- fallback: a plain PIL stick figure, no ComfyUI needed -----------------

def render_stick_still(beat: Beat, width: int, height: int):
    """A static stand-in for a `stick_scene` motion render that failed: the
    same rig (head, torso, 2-segment arms/legs) in a plain standing pose,
    drawn over the beat's own already-generated background picture when
    there is one (STICK_WORLD_PLAN.md SW2: `bg_image`, stashed by
    `annotate_stick_backgrounds`) or on the same plain ground the
    composition would have picked otherwise, with the caption if there was
    one. Never raises -- the caller (presentation/motion.py::
    render_fallback) treats any exception as "no fallback for this beat"."""
    from PIL import Image, ImageDraw, ImageFont

    data = beat.data or {}
    ground = ground_for_scene(data.get("scene") or beat.topic or "")
    bg_color = {"underwater": (11, 43, 64), "night": (21, 21, 29)}.get(ground, (253, 253, 251))
    fg = (223, 239, 246) if ground == "underwater" else (
        (243, 234, 211) if ground == "night" else (26, 26, 26))

    image = Image.new("RGB", (width, height), bg_color)
    bg_path = data.get("bg_image")
    if bg_path and Path(bg_path).exists():
        try:
            with Image.open(bg_path) as src:
                picture = src.convert("RGB")
            cover_scale = max(width / picture.width, height / picture.height)
            resized = picture.resize(
                (max(1, round(picture.width * cover_scale)), max(1, round(picture.height * cover_scale))),
                Image.Resampling.LANCZOS)
            left = max(0, (resized.width - width) // 2)
            top = max(0, (resized.height - height) // 2)
            image = resized.crop((left, top, left + width, top + height))
        except Exception as e:  # noqa: BLE001 - the picture is a bonus, never required
            logger.warning("Stick fallback background %s failed: %s", bg_path, e)

    draw = ImageDraw.Draw(image)

    scale = height * 0.46
    line_width = max(3, round(scale * 0.018))
    cx = width * 0.5
    hip_y = height * 0.84 - scale * 0.4
    shoulder_y = hip_y - scale * 0.33
    head_r = scale * 0.11
    head_y = shoulder_y - scale * 0.035 - head_r
    limb = scale * 0.17

    draw.ellipse([cx - head_r, head_y - head_r, cx + head_r, head_y + head_r],
                outline=fg, width=line_width)
    draw.line([(cx, hip_y), (cx, shoulder_y)], fill=fg, width=line_width)
    draw.line([(cx, shoulder_y), (cx - limb, shoulder_y + limb)], fill=fg, width=line_width)
    draw.line([(cx, shoulder_y), (cx + limb, shoulder_y + limb)], fill=fg, width=line_width)
    draw.line([(cx, hip_y), (cx - limb * 0.8, hip_y + limb * 1.3)], fill=fg, width=line_width)
    draw.line([(cx, hip_y), (cx + limb * 0.8, hip_y + limb * 1.3)], fill=fg, width=line_width)

    caption = (data.get("caption") or "").strip()
    if caption:
        font = None
        for name in ("segoepr.ttf", "arial.ttf"):
            try:
                font = ImageFont.truetype(name, max(16, round(height * 0.045)))
                break
            except OSError:
                continue
        if font is None:
            font = ImageFont.load_default()
        draw.text((width * 0.5, height * 0.12), caption[:60], fill=fg, font=font, anchor="mm")

    return image
