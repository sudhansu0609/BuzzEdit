# The speaker slot, as a fraction of the canvas: a 3:4 portrait window centred
# on the right. The PNG draws its frame; `place_layout_speakers` puts the live
# picture exactly inside it (same geometry, render/effects.py overlay maths).
SLOT_CENTRE = (0.835, 0.5)
SLOT_HEIGHT = 0.40
SLOT_ASPECT = 0.75


def _slot_rect(width: int, height: int) -> Tuple[int, int, int, int]:
    h = int(round(height * SLOT_HEIGHT))
    w = int(round(h * SLOT_ASPECT))
    cx, cy = width * SLOT_CENTRE[0], height * SLOT_CENTRE[1]
    return int(cx - w / 2), int(cy - h / 2), int(cx + w / 2), int(cy + h / 2)


# --- small drawing helpers -----------------------------------------------------------------

def _rgba(size: Tuple[int, int]):
    from PIL import Image
    return Image.new("RGBA", size, (0, 0, 0, 0))


def _shadow(base, box: Tuple[int, int, int, int], radius: int, blur: int = 28,
            offset: int = 14, alpha: int = 70) -> None:
    from PIL import Image, ImageDraw, ImageFilter
    layer = Image.new("RGBA", base.size, (0, 0, 0, 0))
    x0, y0, x1, y1 = box
    ImageDraw.Draw(layer).rounded_rectangle((x0, y0 + offset, x1, y1 + offset), radius,
                                            fill=(0, 0, 0, alpha))
    base.alpha_composite(layer.filter(ImageFilter.GaussianBlur(blur)))


def _speaker_frame(image, width: int, height: int) -> None:
    """The white rounded frame (and its shadow) the live speaker sits in."""
    from PIL import ImageDraw
    x0, y0, x1, y1 = _slot_rect(width, height)
    pad = max(6, height // 110)
    box = (x0 - pad, y0 - pad, x1 + pad, y1 + pad)
    _shadow(image, box, radius=pad * 3)
    ImageDraw.Draw(image).rounded_rectangle(box, pad * 3, fill=WHITE + (255,))


_MARK_RE = re.compile(r"(\*[^*]+\*|==[^=]+==)")


def _tokens(text: str) -> List[Tuple[str, bool]]:
    """Words with a flag for "highlighted": `*word*` or `==phrase==` marks."""
    out: List[Tuple[str, bool]] = []
    for part in _MARK_RE.split(text or ""):
        if not part:
            continue
        marked = (part.startswith("*") and part.endswith("*")) or \
                 (part.startswith("==") and part.endswith("=="))
        body = part.strip("*=") if marked else part
        words = body.split()
        # Punctuation straight after a marked phrase ("*more money*,") belongs
        # to the last word, not to a word of its own with a space before it.
        if words and out and not marked and not body[:1].isspace() and not words[0][:1].isalnum():
            last, last_marked = out.pop()
            out.append((last + words.pop(0), last_marked))
        for word in words:
            out.append((word, marked))
    return out


def plain(text: str) -> str:
    return " ".join(w for w, _ in _tokens(text))


def _layout_words(draw, tokens: List[Tuple[str, bool]], font, max_width: float
                  ) -> List[List[Tuple[str, bool, float]]]:
    space = draw.textlength(" ", font=font)
    lines: List[List[Tuple[str, bool, float]]] = [[]]
    used = 0.0
    for word, marked in tokens:
        w = draw.textlength(word, font=font)
        if lines[-1] and used + space + w > max_width:
            lines.append([])
            used = 0.0
        used += (space if lines[-1] else 0.0) + w
        lines[-1].append((word, marked, w))
    return [line for line in lines if line]


def _fit(draw, tokens, font_fn, max_width: float, max_height: float, start: int,
         minimum: int, spacing: float = 1.22):
    size = start
    while size > minimum:
        font = font_fn(size)
        lines = _layout_words(draw, tokens, font, max_width)
        if len(lines) * size * spacing <= max_height:
            return font, lines, size
        size = int(size * 0.92)
    font = font_fn(minimum)
    return font, _layout_words(draw, tokens, font, max_width), minimum


def _draw_marked_lines(draw, lines, font, size: int, x: float, y: float, colour, marked_colour,
                       marker: Optional[Tuple[int, int, int]] = None, spacing: float = 1.22,
                       align_centre_width: Optional[float] = None) -> float:
    space = draw.textlength(" ", font=font)
    for line in lines:
        line_w = sum(w for _, _, w in line) + space * (len(line) - 1)
        cx = x + (align_centre_width - line_w) / 2 if align_centre_width else x
        for word, marked, w in line:
            if marked and marker is not None:
                pad = size * 0.12
                draw.rectangle((cx - pad, y + size * 0.12, cx + w + pad, y + size * 1.08), fill=marker)
            draw.text((cx, y), word, font=font,
                      fill=marked_colour if marked else colour)
            cx += w + space
        y += size * spacing
    return y


# --- full-frame cards -------------------------------------------------------------------------

def render_statement_card(text: str, width: int, height: int, with_speaker: bool = True):
    from PIL import Image, ImageDraw
    image = Image.new("RGBA", (width, height), CANVAS + (255,))
    if with_speaker:
        _speaker_frame(image, width, height)
    draw = ImageDraw.Draw(image)
    left = width * 0.07
    right = (_slot_rect(width, height)[0] - width * 0.05) if with_speaker else width * 0.93
    font, lines, size = _fit(draw, _tokens(text), lambda s: _serif_font(s, bold=True),
                             right - left, height * 0.72, int(height * 0.1), int(height * 0.04))
    block = len(lines) * size * 1.22
    _draw_marked_lines(draw, lines, font, size, left, (height - block) / 2, INK, ACCENT)
    return image.convert("RGB")


def frame_canvas_card(picture_path: str, width: int, height: int, caption: str = "",
                      with_speaker: bool = True):
    """A generated picture as a floating rounded card on the canvas."""
    from PIL import Image, ImageDraw, ImageOps
    image = Image.new("RGBA", (width, height), CANVAS + (255,))
    if with_speaker:
        _speaker_frame(image, width, height)
    card_w = int(width * (0.68 if with_speaker else 0.82))
    card_h = int(card_w * 9 / 16)
    x0 = int(width * 0.04) if with_speaker else (width - card_w) // 2
    y0 = (height - card_h) // 2
    radius = max(12, height // 45)
    _shadow(image, (x0, y0, x0 + card_w, y0 + card_h), radius)
    picture = ImageOps.fit(Image.open(picture_path).convert("RGB"), (card_w, card_h),
                           Image.LANCZOS)
    mask = Image.new("L", (card_w, card_h), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, card_w, card_h), radius, fill=255)
    image.paste(picture, (x0, y0), mask)
    if caption:
        draw = ImageDraw.Draw(image)
        size = int(height * 0.036)
        font = _serif_font(size, bold=True)
        tx, ty = x0 + card_w * 0.04, y0 + card_h - size * 2.1
        draw.text((tx + 2, ty + 2), caption, font=font, fill=(0, 0, 0, 160))
        draw.text((tx, ty), caption, font=font, fill=WHITE)
    return image.convert("RGB")


def render_source_quote(source: str, quote: str, width: int, height: int,
                        background: Optional[str] = None):
    from PIL import Image, ImageDraw, ImageEnhance, ImageFilter, ImageOps
    if background and Path(background).exists():
        base = ImageOps.fit(Image.open(background).convert("RGB"), (width, height), Image.LANCZOS)
        base = ImageEnhance.Brightness(base.filter(ImageFilter.GaussianBlur(3))).enhance(0.38)
    else:
        base = Image.new("RGB", (width, height), (18, 18, 20))
        glow = Image.new("L", (width, height), 0)
        ImageDraw.Draw(glow).ellipse((-width * 0.2, -height * 0.4, width * 0.8, height * 0.9), fill=60)
        base = Image.composite(Image.new("RGB", (width, height), (70, 40, 30)), base,
                               glow.filter(ImageFilter.GaussianBlur(160)))
    draw = ImageDraw.Draw(base)
    left, top = width * 0.08, height * 0.2
    label = f"SOURCE: {source.upper()}" if source else "SOURCE"
    label_font = _font(int(height * 0.034), bold=True)
    draw.text((left, top), label, font=label_font, fill=MARKER)
    draw.line((left, top + height * 0.055, left + width * 0.18, top + height * 0.055),
              fill=MARKER, width=max(2, height // 360))
    font, lines, size = _fit(draw, _tokens(quote), lambda s: _serif_font(s, bold=True),
                             width * 0.78, height * 0.5, int(height * 0.06), int(height * 0.032))
    _draw_marked_lines(draw, lines, font, size, left, top + height * 0.1, (240, 238, 232), (20, 20, 20),
                       marker=MARKER)
    return base


def render_document(fmt: str, title: str, body: str, width: int, height: int, site: str = ""):
    """`fmt` "web": a browser page; "book": a printed page. Marked phrases get
    the highlighter. The page is drawn tall, then trimmed to its text and
    centred, so a short excerpt is not a sheet of blank paper."""
    from PIL import Image, ImageDraw, ImageFilter
    paper = WHITE if fmt == "web" else (240, 230, 208)
    page_w, max_h = int(width * 0.74), int(height * 0.86)
    page = Image.new("RGB", (page_w, max_h), paper)
    used = _draw_document_page(page, fmt, title, body, width, height, site)
    page = page.crop((0, 0, page_w, min(max_h, max(int(height * 0.42), used))))
    image = Image.new("RGB", (width, height), (38, 38, 42) if fmt == "web" else (58, 50, 42))
    x0, y0 = (width - page.width) // 2, (height - page.height) // 2
    shadow = Image.new("L", (width, height), 0)
    ImageDraw.Draw(shadow).rectangle((x0 + 10, y0 + 18, x0 + page.width + 10, y0 + page.height + 18),
                                     fill=150)
    image.paste((0, 0, 0), (0, 0), shadow.filter(ImageFilter.GaussianBlur(24)))
    image.paste(page, (x0, y0))
    return image


def _draw_document_page(image, fmt: str, title: str, body: str, width: int, height: int,
                        site: str) -> int:
    """Draw onto a page-sized image; returns how far down the text reached."""
    from PIL import ImageDraw
    draw = ImageDraw.Draw(image)
    page_w, page_h = image.size
    x0 = y0 = 0
    pad = page_w * 0.06
    y = y0 + pad * 0.6
    if fmt == "web":
        bar = int(height * 0.05)
        draw.rectangle((x0, y0, x0 + page_w, y0 + bar), fill=(232, 232, 236))
        for i, colour in enumerate(((236, 95, 86), (245, 190, 60), (98, 196, 86))):
            r = bar * 0.16
            cx = x0 + bar * 0.5 + i * bar * 0.45
            draw.ellipse((cx - r, y0 + bar / 2 - r, cx + r, y0 + bar / 2 + r), fill=colour)
        url_font = _font(int(bar * 0.38), bold=False)
        draw.rounded_rectangle((x0 + bar * 2, y0 + bar * 0.2, x0 + page_w - bar, y0 + bar * 0.8),
                               bar * 0.3, fill=WHITE)
        draw.text((x0 + bar * 2.3, y0 + bar * 0.3), site or "www.example.com", font=url_font,
                  fill=MUTED)
        y = y0 + bar + pad * 0.6
    else:
        head_font = _serif_font(int(height * 0.03), bold=True)
        draw.text((x0 + pad, y), f"Book Source: {site}" if site else "Book Source", font=head_font,
                  fill=(90, 70, 50))
        y += height * 0.06
    title_font, title_lines, title_size = _fit(
        draw, _tokens(title), lambda s: _serif_font(s, bold=True), page_w - 2 * pad,
        page_h * 0.28, int(height * 0.06), int(height * 0.03))
    y = _draw_marked_lines(draw, title_lines, title_font, title_size, x0 + pad, y, INK, INK,
                           marker=MARKER)
    y += height * 0.02
    body_font, body_lines, body_size = _fit(
        draw, _tokens(body), lambda s: _serif_font(s, bold=False), page_w - 2 * pad,
        y0 + page_h - pad - y, int(height * 0.042), int(height * 0.022), spacing=1.45)
    y = _draw_marked_lines(draw, body_lines, body_font, body_size, x0 + pad, y, (60, 58, 56),
                           (20, 20, 20), marker=MARKER, spacing=1.45)
    return int(y + pad * 0.8)


def render_timeline(ticks: Sequence[str], active: int, headline: str, caption: str,
                    width: int, height: int):
    from PIL import Image, ImageDraw
    image = Image.new("RGB", (width, height), (16, 18, 20))
    draw = ImageDraw.Draw(image)
    if headline:
        font, lines, size = _fit(draw, _tokens(headline), lambda s: _font(s, bold=True),
                                 width * 0.8, height * 0.34, int(height * 0.2), int(height * 0.08))
        block = len(lines) * size * 1.1
        _draw_marked_lines(draw, lines, font, size, 0, height * 0.36 - block / 2, (126, 232, 120),
                           MARKER, spacing=1.1, align_centre_width=width)
    if caption:
        cap_font = _font(int(height * 0.034), bold=False)
        cap_w = draw.textlength(caption, font=cap_font)
        draw.text(((width - cap_w) / 2, height * 0.56), caption, font=cap_font, fill=(200, 200, 200))
    ruler_y = height * 0.7
    left, right = width * 0.1, width * 0.9
    draw.line((left, ruler_y, right, ruler_y), fill=(210, 210, 210), width=max(2, height // 400))
    count = max(1, len(ticks))
    tick_font = _font(int(height * 0.03), bold=True)
    for i, label in enumerate(ticks):
        x = left + (right - left) * (i / (count - 1) if count > 1 else 0.5)
        on = i == active
        draw.line((x, ruler_y - height * 0.025, x, ruler_y + height * 0.025),
                  fill=ACCENT if on else (210, 210, 210), width=max(2, height // 300))
        tw = draw.textlength(label, font=tick_font)
        draw.text((x - tw / 2, ruler_y + height * 0.035), label, font=tick_font,
                  fill=ACCENT if on else (190, 190, 190))
        if on:
            r = height * 0.014
            draw.ellipse((x - r, ruler_y - r, x + r, ruler_y + r), fill=ACCENT)
    return image


# --- overlays ---------------------------------------------------------------------------------

def render_pill(text: str, height: int, accent: bool = False):
    from PIL import ImageDraw
    size = int(height * 0.04)
    font = _serif_font(size, bold=True)
    probe = ImageDraw.Draw(_rgba((10, 10)))
    tw = probe.textlength(text, font=font)
    pad_x, pad_y = size * 0.75, size * 0.45
    w, h = int(tw + 2 * pad_x), int(size + 2 * pad_y)
    margin = int(size * 0.8)
    image = _rgba((w + 2 * margin, h + 2 * margin))
    _shadow(image, (margin, margin, margin + w, margin + h), radius=h // 2, blur=10, offset=4, alpha=60)
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((margin, margin, margin + w, margin + h), h // 2,
                           fill=(ACCENT if accent else WHITE) + (255,))
    draw.text((margin + pad_x, margin + pad_y - size * 0.1), text, font=font,
              fill=WHITE if accent else INK)
    return image


def render_numbered_point(number: str, text: str, height: int):
    from PIL import ImageDraw
    size = int(height * 0.044)
    probe = ImageDraw.Draw(_rgba((10, 10)))
    max_text_w = height * 0.95
    font, lines, size = _fit(probe, _tokens(text), lambda s: _serif_font(s, bold=True),
                             max_text_w, size * 1.25 * 2, size, int(height * 0.028), spacing=1.25)
    lines = lines[:2]
    space = probe.textlength(" ", font=font)
    tw = max(sum(w for _, _, w in line) + space * (len(line) - 1) for line in lines)
    circle = int(height * 0.042 * 1.7)
    pad = int(height * 0.042 * 0.6)
    text_h = size * 1.25 * len(lines)
    w, h = int(pad * 3 + circle + tw), int(max(circle, text_h) + pad * 1.4)
    margin = int(size * 0.8)
    image = _rgba((w + 2 * margin, h + 2 * margin))
    _shadow(image, (margin, margin, margin + w, margin + h), radius=h // 4, blur=14, offset=6, alpha=60)
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((margin, margin, margin + w, margin + h), h // 4, fill=WHITE + (255,))
    cx0, cy0 = margin + pad, margin + (h - circle) // 2
    draw.ellipse((cx0, cy0, cx0 + circle, cy0 + circle), fill=ACCENT + (255,))
    num_font = _serif_font(int(circle * 0.62), bold=True)
    nw = draw.textlength(number, font=num_font)
    draw.text((cx0 + (circle - nw) / 2, cy0 + circle * 0.12), number, font=num_font, fill=WHITE)
    _draw_marked_lines(draw, lines, font, size, cx0 + circle + pad,
                       margin + (h - text_h) / 2 - size * 0.08, INK, ACCENT, spacing=1.25)
    return image


# --- colour looks -------------------------------------------------------------------------------

def apply_look(path: str, look: str) -> str:
    """A graded copy of a still (`<name>.<look>.png`), or the path unchanged
    for an unknown look or an unreadable file."""
    look = (look or "").strip().lower()
    if look not in LOOKS:
        return path
    source = Path(path)
    target = source.with_name(f"{source.stem}.{look}.png")
    if target.exists():
        return str(target)
    try:
        from PIL import Image, ImageEnhance, ImageOps
        image = Image.open(source).convert("RGB")
        gray = ImageOps.grayscale(image)
        if look == "bw":
            out = ImageEnhance.Contrast(gray).enhance(1.15).convert("RGB")
        elif look == "noir":
            out = ImageOps.autocontrast(ImageEnhance.Contrast(gray).enhance(1.6), cutoff=2).convert("RGB")
        elif look == "sepia":
            out = ImageOps.colorize(gray, black=(30, 18, 8), white=(250, 232, 196), mid=(160, 118, 72))
        elif look == "red_duotone":
            out = ImageOps.colorize(ImageEnhance.Contrast(gray).enhance(1.25),
                                    black=(12, 4, 6), white=(255, 214, 200), mid=(170, 28, 38))
        elif look == "blue_duotone":
            out = ImageOps.colorize(gray, black=(6, 10, 26), white=(214, 234, 255), mid=(40, 90, 170))
        elif look == "warm":
            r, g, b = image.split()
            out = Image.merge("RGB", (r.point(lambda v: min(255, int(v * 1.08 + 6))), g,
                                      b.point(lambda v: int(v * 0.88))))
        else:  # cool
            r, g, b = image.split()
            out = Image.merge("RGB", (r.point(lambda v: int(v * 0.9)), g,
                                      b.point(lambda v: min(255, int(v * 1.08 + 6)))))
        out.save(target)
        return str(target)
    except Exception as e:
        logger.warning("Look %s on %s failed: %s", look, path, e)
        return path


def post_process_generated(assets: List[Asset], beats: Sequence[Beat], width: int,
                           height: int) -> List[Asset]:
    """Looks on generated stills, then canvas framing for `canvas_card`. A clip
    (video) keeps its motion and is left alone."""
    by_id = {b.id: b for b in beats}
    for asset in assets:
        beat = by_id.get(asset.beat_id)
        if beat is None or asset.kind != "image":
            continue
        data = beat.data or {}
        look = data.get("look")
        if look:
            asset.path = apply_look(asset.path, str(look))
        if beat.kind == "canvas_card":
            key = hashlib.sha1(f"{asset.path}|{data.get('caption')}|{width}x{height}|"
                               f"{data.get('with_speaker', True)}".encode()).hexdigest()[:12]
            target = Path(asset.path).with_name(f"canvas_{key}.png")
            if not target.exists():
                try:
                    frame_canvas_card(asset.path, width, height, str(data.get("caption") or ""),
                                      bool(data.get("with_speaker", True))).save(target)
                except Exception as e:
                    logger.warning("Canvas card for %s failed: %s", beat.id, e)
                    continue
            asset.path, asset.width, asset.height = str(target), width, height
    return assets


