"""Designed graphics: the explainer-style layouts and documentary cards.

Studied from two reference styles (2026-09): Ali Abdaal's clean explainers and
Nitish Rajput's documentary storytelling. Every graphic here is drawn with PIL
and cached by its content, like the charts and newspapers, so none of them
needs ComfyUI and all of them work for any channel.

Full-frame cutaways (placed by `placement.place_broll` like any B-roll):

* ``statement_card`` -- a sentence set big in serif on an off-white canvas,
  the words marked ``*like this*`` in the accent colour, with a slot on the
  right where the speaker stays live (`place_layout_speakers`).
* ``canvas_card`` -- a generated picture floated in a rounded, shadowed card
  on the off-white canvas, an optional caption chip on it, and the speaker
  live in the right-hand slot. Generated by ComfyUI as a still, then framed
  here (`frame_canvas_card`).
* ``source_quote`` -- "SOURCE: ..." over a darkened picture (or a dark
  gradient) with the cited sentence and its ``==highlighted==`` phrase.
* ``document`` -- a web article (browser chrome) or a book page, headline and
  body with ``==highlighted==`` phrases under a marker sweep.
* ``timeline`` -- a big figure over a ruler of dates, one date marked.

Overlays on the speaker (placed here, not as cutaways):

* ``pill_labels`` -- two to four rounded labels popping in one by one on the
  side away from the face.
* ``numbered_point`` -- a numbered white bar ("1  Super friendly for
  beginners").
* ``name_title`` -- NAME and a subtitle, clean type, bottom right above the
  captions.

Modifiers:

* ``look`` on any generated still (``broll_image``/``canvas_card``):
  ``bw``, ``noir``, ``sepia``, ``red_duotone``, ``blue_duotone``, ``warm``,
  ``cool`` (`apply_look`).
* The "Generative AI" tag on every generated picture that goes on screen
  (`place_ai_labels`, `settings.ai_label`).
"""

