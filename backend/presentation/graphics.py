def render_graphic_assets(beats: Sequence[Beat], project_dir: Path, width: int, height: int,
                          generated: Sequence[Asset] = ()) -> Tuple[List[Asset], List[Dict[str, str]]]:
    """PNG cutaways for statement cards, source quotes, documents and timelines."""
    assets: List[Asset] = []
    failures: List[Dict[str, str]] = []
    wanted = [b for b in beats if b.kind in DRAWN_CUTAWAY_KINDS]
    if not wanted:
        return assets, failures
    directory = Path(project_dir) / "assets" / "graphics"
    directory.mkdir(parents=True, exist_ok=True)
    pictures = {a.beat_id: a.path for a in generated if a.kind == "image"}
    for beat in wanted:
        data = dict(beat.data or {})
        key = hashlib.sha1(f"{beat.kind}|{beat.text}|{beat.subtext}|{sorted(data.items())!r}|"
                           f"{width}x{height}".encode()).hexdigest()[:12]
        path = directory / f"{beat.kind}_{key}.png"
        if not path.exists():
            try:
                if beat.kind == "statement_card":
                    image = render_statement_card(beat.text or "", width, height,
                                                  bool(data.get("with_speaker", True)))
                elif beat.kind == "source_quote":
                    image = render_source_quote(str(data.get("source") or ""), beat.text or "",
                                                width, height, pictures.get(beat.id))
                elif beat.kind == "document":
                    image = render_document(str(data.get("format") or "web"), beat.text or "",
                                            beat.subtext or "", width, height,
                                            str(data.get("site") or ""))
                else:
                    ticks = [str(t) for t in (data.get("ticks") or [])] or ["", ""]
                    image = render_timeline(ticks, int(data.get("active", len(ticks) - 1)),
                                            beat.text or "", beat.subtext or "", width, height)
                image.save(path)
            except Exception as e:
                logger.warning("%s for %r failed: %s", beat.kind, beat.topic, e)
                failures.append({"beat_id": beat.id, "reason": f"render failed: {e}"})
                continue
        assets.append(Asset(beat_id=beat.id, kind="image", path=str(path), width=width,
                            height=height, cache_hit=True))
    return assets, failures


# --- the live speaker in a layout's slot --------------------------------------------------

def _speaker_crop(face_x: float, source_w: int, source_h: int) -> Tuple[float, float]:
    """(crop_left, crop_right) giving a 3:4 window centred on the face."""
    keep = min(1.0, source_h * SLOT_ASPECT / max(1, source_w))
    centre = (face_x + 1.0) / 2.0
    left = min(max(0.0, centre - keep / 2), 1.0 - keep)
    return left, max(0.0, 1.0 - keep - left)


def place_layout_speakers(timeline: Timeline, beats: Sequence[Beat],
                          face_anchors: Optional[Dict[str, Tuple[float, float]]] = None) -> int:
    """The speaker, live, inside the slot of every placed statement/canvas card."""
    clear_generated(timeline, LAYOUT_ORIGIN)
    wanted = {b.id for b in beats if b.kind in SPEAKER_LAYOUT_KINDS
              and (b.data or {}).get("with_speaker", True)}
    if not wanted:
        return 0
    face_anchors = face_anchors or {}
    width, height = timeline.width or 1920, timeline.height or 1080
    slot_h = _slot_rect(width, height)[3] - _slot_rect(width, height)[1]
    scale = slot_h / height
    pos_x = SLOT_CENTRE[0] * 2 - 1.0
    pos_y = SLOT_CENTRE[1] * 2 - 1.0
    v1 = sorted((i for i in timeline.items if i.track == "V1" and i.kind == "media" and i.enabled),
                key=lambda i: i.timeline_start_frame)
    count = 0
    for cut in [i for i in timeline.items if i.kind == "media" and i.source_id
                and any(i.source_id.startswith(f"src_broll_{b}_") for b in wanted)]:
        for segment in v1:
            lo = max(cut.timeline_start_frame, segment.timeline_start_frame)
            hi = min(cut.timeline_end_frame, segment.timeline_end_frame)
            if hi - lo <= 2 or not segment.source_id:
                continue
            source = timeline.sources.get(segment.source_id)
            src_w = (source.width if source and source.width else width)
            src_h = (source.height if source and source.height else height)
            face_x = face_anchors.get(segment.id, (0.0, 0.0))[0]
            crop_left, crop_right = _speaker_crop(face_x, src_w, src_h)
            offset = lo - segment.timeline_start_frame
            item = clip_ops.add_media_item(
                timeline, segment.source_id, LAYOUT_SPEAKER_TRACK, lo,
                segment.source_start_frame + offset,
                segment.source_start_frame + offset + (hi - lo), origin=LAYOUT_ORIGIN)
            item.mute = True
            item.label = "layout: speaker"
            clip_ops.set_transform(timeline, item.id, {
                "scale": scale, "pos_x": pos_x, "pos_y": pos_y,
                "crop_left": crop_left, "crop_right": crop_right})
        count += 1
    if count:
        timeline.recalculate_duration()
        timeline.revision += 1
    return count


# --- overlays on the speaker ------------------------------------------------------------------

def _inside_pos_x(side: float, overlay_w: int, width: int, reach: float) -> float:
    """pos_x for an overlay pushed `reach` of the way toward `side`, pulled in
    so the whole overlay stays inside the frame with a margin."""
    margin = width * 0.03
    limit = max(0.0, (width - overlay_w - 2 * margin) / width)
    return side * min(reach, limit)


def _overlaps(start: float, end: float, windows: Sequence[Tuple[float, float]]) -> bool:
    return any(start < e and s < end for s, e in windows)


def _register_png(timeline: Timeline, path: Path, duration_s: float, image) -> str:
    source_id = f"src_overlay_{path.stem}"
    timeline.sources[source_id] = SourceFile(
        id=source_id, path=str(path), duration_seconds=max(1.0, duration_s),
        width=image.width, height=image.height, fps_num=timeline.fps_num,
        fps_den=timeline.fps_den, has_audio=False, kind="image")
    return source_id


def place_overlays(timeline: Timeline, beats: Sequence[Beat], program, project_dir: Path,
                   busy: Sequence[Tuple[float, float]] = (),
                   face_anchors: Optional[Dict[str, Tuple[float, float]]] = None) -> Dict[str, int]:
    """Pill labels, numbered points and name titles, each at its beat's moment,
    on the side away from the speaker's face, never over a full-frame cutaway."""
    clear_generated(timeline, OVERLAY_ORIGIN)
    counts: Dict[str, int] = {}
    wanted = sorted((b for b in beats if b.kind in OVERLAY_KINDS), key=lambda b: b.start_s)
    if not wanted:
        return counts
    face_anchors = face_anchors or {}
    width, height = timeline.width or 1920, timeline.height or 1080
    fps_num, fps_den = timeline.fps_num, timeline.fps_den
    directory = Path(project_dir) / "assets" / "graphics"
    directory.mkdir(parents=True, exist_ok=True)
    taken: List[Tuple[float, float]] = []
    for beat in wanted:
        start = max(0.0, beat.start_s)
        end = min(program.duration_s, max(beat.end_s, start + 2.5))
        if _overlaps(start, end, busy) or _overlaps(start, end, taken):
            continue
        segment = program.segment_at(start)
        face_x = (face_anchors.get(segment.item_id) or (0.0, 0.0))[0] if segment else 0.0
        side = -1.0 if face_x >= 0.0 else 1.0     # away from the face
        data = beat.data or {}
        if beat.kind == "name_title":
            _place_name_title(timeline, beat, start, end)
        elif beat.kind == "pill_labels":
            items = [str(x) for x in (data.get("items") or []) if str(x).strip()][:4]
            if not items:
                continue
            step = min(0.45, (end - start) / (len(items) + 1))
            gap = 0.14
            top = -gap * (len(items) - 1) / 2
            for index, label in enumerate(items):
                image = render_pill(label, height, accent=bool(data.get("accent_first")) and index == 0)
                path = directory / f"pill_{hashlib.sha1(f'{label}|{height}'.encode()).hexdigest()[:10]}.png"
                if not path.exists():
                    image.save(path)
                appear = start + index * step
                source_id = _register_png(timeline, path, end - appear, image)
                item = clip_ops.add_media_item(
                    timeline, source_id, OVERLAY_TRACK, time_to_frame(appear, fps_num, fps_den), 0,
                    max(1, time_to_frame(end - appear, fps_num, fps_den)), origin=OVERLAY_ORIGIN)
                item.label = f"pill: {label[:24]}"
                clip_ops.set_transform(timeline, item.id, {
                    "scale": image.width / width,
                    "pos_x": _inside_pos_x(side, image.width, width, 0.55),
                    "pos_y": top + gap * index * 2})
        else:
            number = str(data.get("number") or "1")
            image = render_numbered_point(number, plain(beat.text or ""), height)
            path = directory / f"point_{hashlib.sha1(f'{number}|{beat.text}|{height}'.encode()).hexdigest()[:10]}.png"
            if not path.exists():
                image.save(path)
            source_id = _register_png(timeline, path, end - start, image)
            item = clip_ops.add_media_item(
                timeline, source_id, OVERLAY_TRACK, time_to_frame(start, fps_num, fps_den), 0,
                max(1, time_to_frame(end - start, fps_num, fps_den)), origin=OVERLAY_ORIGIN)
            item.label = f"point {number}: {(beat.text or '')[:24]}"
            clip_ops.set_transform(timeline, item.id, {
                "scale": image.width / width,
                "pos_x": _inside_pos_x(side, image.width, width, 0.5), "pos_y": -0.62})
        counts[beat.kind] = counts.get(beat.kind, 0) + 1
        taken.append((start, end))
    if counts:
        timeline.recalculate_duration()
        timeline.revision += 1
    return counts


def _place_name_title(timeline: Timeline, beat: Beat, start: float, end: float) -> None:
    fps_num, fps_den = timeline.fps_num, timeline.fps_den
    frames = max(1, time_to_frame(end - start, fps_num, fps_den))
    first = time_to_frame(start, fps_num, fps_den)
    name = clip_ops.add_text_item(
        timeline, (beat.text or "").upper(), first, frames, track=NAME_TITLE_TRACK,
        style={"font_family": "Montserrat", "font_size": 58, "bold": True, "color": "white",
               "stroke_width": 3, "stroke_color": "black@0.6", "align": "right",
               "pos_x": 0.92, "pos_y": TEXT_ZONE_MAX_POS_Y - 0.1,
               "animation": "fade", "animation_duration": 0.3})
    name.origin = OVERLAY_ORIGIN
    name.label = f"name: {beat.text}"
    if beat.subtext:
        sub = clip_ops.add_text_item(
            timeline, beat.subtext.upper(), first, frames, track=NAME_TITLE_TRACK,
            style={"font_family": "Montserrat", "font_size": 30, "bold": False,
                   "color": "#E8E8E8", "stroke_width": 2, "stroke_color": "black@0.6",
                   "align": "right", "pos_x": 0.92, "pos_y": TEXT_ZONE_MAX_POS_Y,
                   "animation": "fade", "animation_duration": 0.3})
        sub.origin = OVERLAY_ORIGIN
        sub.label = f"name sub: {beat.subtext}"


# --- the disclosure tag -----------------------------------------------------------------------

def place_ai_labels(timeline: Timeline, generated_beat_ids: Sequence[str]) -> int:
    """"Generative AI" in the bottom-left corner over every generated picture
    on screen. YouTube expects realistic synthetic imagery to be disclosed;
    the reference documentary tags every one of its AI stills the same way."""
    clear_generated(timeline, AI_LABEL_ORIGIN)
    ids = set(generated_beat_ids)
    if not ids:
        return 0
    count = 0
    for item in [i for i in timeline.items if i.kind == "media" and i.source_id
                 and i.track != "V1" and i.origin in ("broll",)]:
        beat_id = item.source_id[len("src_broll_"):].rsplit("_", 1)[0] \
            if item.source_id.startswith("src_broll_") else None
        if beat_id not in ids:
            continue
        label = clip_ops.add_text_item(
            timeline, AI_LABEL_TEXT, item.timeline_start_frame, item.duration_frames,
            track=AI_LABEL_TRACK,
            style={"font_family": "Inter", "font_size": 22, "bold": False, "color": "white@0.75",
                   "stroke_width": 1, "stroke_color": "black@0.5", "align": "left",
                   "pos_x": -0.96, "pos_y": 0.93, "animation": "none"})
        label.origin = AI_LABEL_ORIGIN
        label.label = "ai label"
        count += 1
    return count
