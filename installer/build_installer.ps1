# Builds installer\<Name> Setup.exe and installer\Uninstall <Name>.exe for the app whose
# installer\ folder holds this script (scripts/app_installer, see README.md).
# Reads installer\app.json, generates AppInfo.cs from it and compiles Setup.cs / Uninstall.cs
# with the .NET Framework csc that ships with Windows -- no SDK or Inno Setup needed.
$ErrorActionPreference = "Stop"
$here = $PSScriptRoot
$root = Split-Path -Parent $here
$app = Get-Content (Join-Path $here "app.json") -Raw -Encoding utf8 | ConvertFrom-Json

foreach ($field in "id", "name", "description", "version", "launch_target", "icon") {
    if (-not $app.$field) { throw "app.json needs `"$field`"" }
}

function CsString([string]$s) { '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }
$publisher = if ($app.publisher) { $app.publisher } else { "Buzzcaf Media" }
$envSummary = if ($app.env_summary) { $app.env_summary } else { "dependencies" }
$setup = if ($null -ne $app.setup_script) { $app.setup_script } else { "installer\setup_env.ps1" }
$launchArgs = if ($app.launch_args) { $app.launch_args } else { "" }
$mb = if ($app.estimated_mb) { [int]$app.estimated_mb } else { 500 }

$info = @"
// Generated by installer\build_installer.ps1 from installer\app.json. Do not edit.
namespace BuzzcafAppSetup
{
    static class AppInfo
    {
        public const string Id = $(CsString $app.id);
        public const string Name = $(CsString $app.name);
        public const string Description = $(CsString $app.description);
        public const string Version = $(CsString $app.version);
        public const string Publisher = $(CsString $publisher);
        public const string LaunchTarget = $(CsString $app.launch_target);
        public const string LaunchArgs = $(CsString $launchArgs);
        public const string Icon = $(CsString $app.icon);
        public const string SetupScript = $(CsString $setup);
        public const string EnvSummary = $(CsString $envSummary);
        public const int EstimatedMB = $mb;
    }
}
"@
$infoPath = Join-Path $env:TEMP ("AppInfo_{0}.cs" -f $app.id)
Set-Content -Path $infoPath -Value $info -Encoding utf8

$csc = "$env:WINDIR\Microsoft.NET\Framework64\v4.0.30319\csc.exe"
if (-not (Test-Path $csc)) { $csc = "$env:WINDIR\Microsoft.NET\Framework\v4.0.30319\csc.exe" }
if (-not (Test-Path $csc)) { throw "csc.exe (.NET Framework 4) not found" }

$icon = Join-Path $root $app.icon
$common = @("/nologo", "/target:winexe", "/optimize+", "/r:System.dll", "/r:System.Windows.Forms.dll", "/r:System.Drawing.dll")
if (Test-Path $icon) { $common += "/win32icon:$icon" } else { Write-Warning "icon not found: $icon (building without one)" }

$targets = @(
    @{ out = Join-Path $here ("{0} Setup.exe" -f $app.name); src = Join-Path $here "Setup.cs"; extra = @() },
    # Uninstall.cs shares Paths with Setup.cs, so Setup.cs is compiled into it too; /main picks the entry point.
    @{ out = Join-Path $here ("Uninstall {0}.exe" -f $app.name); src = Join-Path $here "Uninstall.cs"; extra = @((Join-Path $here "Setup.cs"), "/main:BuzzcafAppSetup.UninstallProgram") }
)
foreach ($t in $targets) {
    $cscArgs = $common + @("/out:$($t.out)", $t.src, $infoPath) + $t.extra
    & $csc @cscArgs
    if ($LASTEXITCODE -ne 0) { throw "compiling $([IO.Path]::GetFileName($t.out)) failed" }
    Write-Host ("built {0} ({1:N0} bytes)" -f $t.out, (Get-Item $t.out).Length)
}
Remove-Item $infoPath -ErrorAction SilentlyContinue
